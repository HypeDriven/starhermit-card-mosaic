// Writes the engine play scripts (tests/native/*.play) that drive the real UI
// through whole rounds: the moves come from the content's own solution (the
// order tests/helpers.mjs solveSession plays), turned into the clicks and
// keys a player uses — click a tray card, press R until it is turned right
// (a rotation drops the selection, so the card is picked up again), click
// its cell. Run after content changes: `npm run gen-play`.
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { journeyContent, lessonContent, instantiate } from '../js/content.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'tests', 'native');
mkdirSync(out, { recursive: true });

/** Clicks and keys placing every solution card still off the board (lowest cell first). */
function solveSteps(content, { skip = new Set() } = {}) {
  const state = instantiate(content);
  const steps = [];
  for (let cell = 0; cell < state.cells.length; cell++) {
    const sol = content.solution[cell];
    if (!sol || state.cells[cell] !== null || skip.has(cell)) continue;
    const card = state.cards[sol.card];
    const slot = state.tray.indexOf(sol.card);
    let rot = ((card.rot % 4) + 4) % 4;
    const want = ((sol.rot || 0) % 4 + 4) % 4;
    while (rot !== want) {
      steps.push(`click Tray slot ${slot + 1},`, 'frames 5', 'key KeyR 2', 'frames 10');
      rot = (rot + 1) % 4;
    }
    const x = cell % content.grid.w, y = Math.floor(cell / content.grid.w);
    steps.push(`click Tray slot ${slot + 1},`, 'frames 5', `click Row ${y + 1} column ${x + 1},`, 'frames 10');
    state.cells[cell] = sol.card;
    state.tray[slot] = null;
  }
  return steps;
}
const write = (name, lines) => writeFileSync(join(out, name), lines.join('\n') + '\n');
const header = (text) => text.split('\n').map((l) => '# ' + l);

// --- the first journey stage, solved by pointer, then the next stage starts
{
  const c = journeyContent(0);
  write('journey-stage.play', [
    ...header('Title → Play → Journey → Stage 1, solved by clicking tray cards and cells\n(generated by tools/gen-play.mjs); the results with stars, then Next stage.'),
    'until 300 Play', 'frames 10', 'save title',
    'click Play', 'until 60 Choose a mode', 'frames 10', 'save modes',
    'click Journey', 'until 60 Chapter 1', 'frames 10', 'save journey',
    'click Stage 1,', 'until 120 Rotate', 'frames 60', 'save play',
    ...solveSteps(c),
    'until 240 Mosaic complete!', 'frames 30', 'expect Score breakdown', 'save results',
    'click Next stage', 'until 120 Rotate', 'frames 20', 'save stage-2',
  ]);
}

// --- lessons: place then recall (the Recall button), finish; the next lesson
{
  const got = lessonContent('lesson-recall');
  const c = got.content;
  const state = instantiate(c);
  const cell = Object.keys(c.solution).map(Number).find((i) => state.cells[i] === null);
  const sol = c.solution[cell];
  const slot = state.tray.indexOf(sol.card);
  const x = cell % c.grid.w, y = Math.floor(cell / c.grid.w);
  write('learn-lesson.play', [
    ...header('Play → Learn → Second Thoughts: place a card, select it and Recall it, then\nfinish (generated by tools/gen-play.mjs); the results offer the next lesson.'),
    'until 300 Play', 'frames 10', 'click Play', 'until 60 Choose a mode', 'frames 10',
    'click Learn', 'until 60 Second Thoughts', 'frames 10', 'save lessons',
    'click Second Thoughts', 'until 120 Place any tray card onto the board.', 'frames 30',
    `click Tray slot ${slot + 1},`, 'frames 5', `click Row ${y + 1} column ${x + 1},`, 'frames 10',
    'until 60 Now recall that card back to the tray.', `click Row ${y + 1} column ${x + 1},`, 'frames 5', 'save lesson-selected',
    'click Recall', 'until 60 Finish the mosaic at your own pace.', 'frames 10', 'save lesson-recalled',
    ...solveSteps(c),
    'until 240 Next lesson', 'frames 20', 'save lesson-results',
  ]);
}

